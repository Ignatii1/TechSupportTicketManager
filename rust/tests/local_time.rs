//! Время без пояса — по смещению этого компьютера (`AssumeLocal`), и при переводе часов: двойное (осень) — по зимнему, как
//! .NET; в пропуске (весна) — смещение до него. Свой файл проверки: пояс задаётся переменной TZ до первого чтения часов
//! (на Windows TZ не действует — там пояс системы).

#[cfg(unix)]
#[test]
fn daylight_saving_edges() {
    use chrono::{TimeZone, Utc};
    use ticketboard::intraservice::parse;
    // SAFETY: в этом файле одна проверка, других потоков, читающих окружение, нет
    unsafe { std::env::set_var("TZ", "Europe/Berlin") };
    let utc = |mo, d, h, mi| Utc.with_ymd_and_hms(2026, mo, d, h, mi, 0).unwrap().fixed_offset();
    // 25.10.2026 в 03:00 летнего часы переводят на 02:00: 02:30 бывает дважды — берём зимнее (+01:00)
    assert_eq!(parse::date("25.10.2026 02:30"), Some(utc(10, 25, 1, 30)));
    // 29.03.2026 в 02:00 часы переводят на 03:00: 02:30 не бывает — смещение до перевода (+01:00)
    assert_eq!(parse::date("2026-03-29T02:30"), Some(utc(3, 29, 1, 30)));
    // обычное время — своё смещение
    assert_eq!(parse::date("12.10.2026 13:44"), Some(utc(10, 12, 11, 44)));
}
